export const dict = { en, bn };
export type Dict = typeof en;
export type ErrKey = Extract<keyof Dict, `err_${string}`>;

const KNOWN_ERRORS = [
  "not_authorized", "invalid_email", "already_member", "invalid_invitation", "invitation_expired",
  "email_mismatch", "business_inactive", "shares_must_total_100", "negative_share",
  "invitation_not_pending", "member_not_active",
];

/** Map a database/RPC error to a translation key. */
export function errorKey(e: { message?: string; code?: string } | null | undefined): ErrKey {
  if (!e) return "err_generic";
  if (e.code === "23505") return "err_invite_pending_exists";
  const hit = KNOWN_ERRORS.find((k) => e.message?.includes(k));
  return (hit ? `err_${hit}` : "err_generic") as ErrKey;
}

export function fmtDate(iso: string | null | undefined, lang: Lang, withTime = false) {
  if (!iso) return "—";
  const d = new Date(iso.length === 10 ? iso + "T00:00:00+06:00" : iso);
  return new Intl.DateTimeFormat(lang === "bn" ? "bn-BD" : "en-GB", {
    timeZone: "Asia/Dhaka", day: "numeric", month: "short", year: "numeric",
    ...(withTime ? { hour: "numeric", minute: "2-digit" } : {}),
  }).format(d);
}

export function fmtNum(n: number, lang: Lang) {
  return new Intl.NumberFormat(lang === "bn" ? "bn-BD" : "en-US", { maximumFractionDigits: 2 }).format(n);
}
